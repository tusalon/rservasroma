-- Lista de espera POR DIA con oferta automatica (07-11-2026).
--
-- Antes: la clienta esperaba UNA hora con UNA profesional; el aviso lo lanzaba el movil que cancelaba y,
-- al liberarse, la hora quedaba abierta para cualquiera. De 601 esperas (ago-nov 2026) solo 1 consiguio
-- su hora y 525 nunca vieron liberarse la suya.
--
-- Ahora:
--   * La clienta se anota al DIA (manana, tarde o cualquiera; su profesional o cualquiera).
--   * Cuando una reserva se cancela, se borra o se mueve, la BASE apunta el hueco (lista_espera_huecos)
--     y llama a la funcion lista-espera, que se lo OFRECE a la primera de la fila que encaje y se lo
--     guarda 30 minutos (estado 'ofrecida'; la app lo oculta a las demas). Si no lo coge, pasa a la
--     siguiente. Un cron cada 5 minutos repasa las ofertas vencidas.
--   * Al reservar ese dia, su espera se cierra sola ('reservada').
--   * Los telefonos dejan de ser legibles con la clave publica: la clienta usa funciones (RPC) que
--     solo devuelven lo suyo, y el panel lee con la sesion del panel (rol panel_salon).
--
-- Estados (tipo 'dia'): esperando -> ofrecida -> reservada | (vence) esperando ; cerrada (la quitan) ;
-- caducada (paso el dia). Las filas viejas tipo 'hora' de dias futuros se pasan a 'dia'.
--
-- ORDEN: PARTE A (no cambia nada de lo que ya funciona) -> desplegar la funcion lista-espera ->
-- publicar la app -> PARTE B (activa los avisos y cierra la lectura publica).
-- Se puede correr dos veces.

-- ================================== PARTE A ==================================

alter table public.lista_espera
    add column if not exists tipo text not null default 'hora',
    add column if not exists franja text not null default 'cualquiera',
    add column if not exists oferta_hora time,
    add column if not exists oferta_hora_fin time,
    add column if not exists oferta_profesional_id integer,
    add column if not exists oferta_profesional_nombre text,
    add column if not exists oferta_hasta timestamptz,
    add column if not exists reserva_id bigint,
    add column if not exists updated_at timestamptz not null default now();

alter table public.lista_espera alter column hora_inicio drop not null;
alter table public.lista_espera alter column profesional_id drop not null;   -- null = cualquier profesional

create index if not exists lista_espera_negocio_fecha_estado_idx
    on public.lista_espera (negocio_id, fecha, estado);

-- Huecos liberados que esperan a ser ofrecidos. Solo los toca la base y la funcion (service role).
create table if not exists public.lista_espera_huecos (
    id bigint generated by default as identity primary key,
    negocio_id uuid not null,
    fecha date not null,
    profesional_id integer not null,
    hora_inicio time not null,
    hora_fin time not null,
    estado text not null default 'abierto',          -- abierto | ofrecido | cerrado
    ofrecido_a bigint,                               -- lista_espera.id con la oferta vigente
    rechazado_por bigint[] not null default '{}',    -- a quien ya se le ofrecio y no lo cogio
    created_at timestamptz not null default now()
);
create index if not exists lista_espera_huecos_abiertos_idx on public.lista_espera_huecos (estado, fecha);
alter table public.lista_espera_huecos enable row level security;
revoke all on public.lista_espera_huecos from anon, authenticated;

-- Ultimos 8 digitos: la misma clienta escribe su numero con y sin prefijo.
create or replace function public.lista_espera_tel(t text)
returns text language sql immutable as $$
    select right(regexp_replace(coalesce(t, ''), '\D', '', 'g'), 8)
$$;

create or replace function public.lista_espera_hoy()
returns date language sql stable as $$
    select (now() at time zone 'America/Havana')::date
$$;

-- --- Funciones para la app de la clienta (solo devuelven lo suyo) -------------------------------------

create or replace function public.lista_espera_unirse(
    p_negocio uuid, p_nombre text, p_whatsapp text, p_servicio text, p_duracion integer,
    p_profesional_id integer, p_profesional_nombre text, p_fecha date, p_franja text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
    if p_negocio is null or p_fecha is null or p_fecha < lista_espera_hoy() then
        return jsonb_build_object('ok', false, 'motivo', 'fecha');
    end if;
    if length(lista_espera_tel(p_whatsapp)) < 6 or coalesce(trim(p_nombre), '') = '' then
        return jsonb_build_object('ok', false, 'motivo', 'datos');
    end if;
    if exists (select 1 from lista_espera
               where negocio_id = p_negocio and fecha = p_fecha and estado in ('esperando', 'ofrecida')
                 and lista_espera_tel(cliente_whatsapp) = lista_espera_tel(p_whatsapp)) then
        return jsonb_build_object('ok', false, 'motivo', 'ya_anotada');
    end if;
    insert into lista_espera (negocio_id, cliente_nombre, cliente_whatsapp, servicio, duracion, profesional_id,
                              profesional_nombre, fecha, franja, tipo, estado)
    values (p_negocio, trim(p_nombre), p_whatsapp, coalesce(p_servicio, ''), p_duracion, p_profesional_id,
            p_profesional_nombre, p_fecha,
            case when p_franja in ('manana', 'tarde') then p_franja else 'cualquiera' end, 'dia', 'esperando')
    returning id into v_id;
    return jsonb_build_object('ok', true, 'id', v_id);
end $$;

create or replace function public.lista_espera_mias(p_negocio uuid, p_whatsapp text)
returns table (id bigint, fecha date, franja text, servicio text, duracion integer, profesional_id integer,
               profesional_nombre text, estado text, oferta_hora time, oferta_hora_fin time,
               oferta_profesional_id integer, oferta_profesional_nombre text, oferta_hasta timestamptz)
language sql stable security definer set search_path = public as $$
    select l.id, l.fecha, l.franja, l.servicio, l.duracion, l.profesional_id, l.profesional_nombre,
           case when l.estado = 'ofrecida' and l.oferta_hasta <= now() then 'esperando' else l.estado end,
           l.oferta_hora, l.oferta_hora_fin, l.oferta_profesional_id, l.oferta_profesional_nombre, l.oferta_hasta
    from lista_espera l
    where l.negocio_id = p_negocio and l.tipo = 'dia' and l.estado in ('esperando', 'ofrecida')
      and l.fecha >= lista_espera_hoy()
      and length(lista_espera_tel(p_whatsapp)) >= 6
      and lista_espera_tel(l.cliente_whatsapp) = lista_espera_tel(p_whatsapp)
    order by l.fecha
$$;

create or replace function public.lista_espera_salir(p_id bigint, p_whatsapp text)
returns boolean language plpgsql security definer set search_path = public as $$
declare v_ok boolean;
begin
    update lista_espera set estado = 'cerrada', updated_at = now()
    where id = p_id and estado in ('esperando', 'ofrecida')
      and length(lista_espera_tel(p_whatsapp)) >= 6
      and lista_espera_tel(cliente_whatsapp) = lista_espera_tel(p_whatsapp);
    v_ok := found;
    if v_ok then
        -- Si tenia una hora guardada, vuelve a quedar libre para la siguiente.
        update lista_espera_huecos set estado = 'abierto', ofrecido_a = null, rechazado_por = rechazado_por || p_id
        where ofrecido_a = p_id;
    end if;
    return v_ok;
end $$;

-- Horas guardadas a otras clientas (sin datos personales): la app las trata como ocupadas.
create or replace function public.lista_espera_retenidas(p_negocio uuid, p_fecha date, p_whatsapp text default '')
returns table (profesional_id integer, hora_inicio time, hora_fin time)
language sql stable security definer set search_path = public as $$
    select l.oferta_profesional_id, l.oferta_hora, l.oferta_hora_fin
    from lista_espera l
    where l.negocio_id = p_negocio and l.fecha = p_fecha and l.estado = 'ofrecida' and l.oferta_hasta > now()
      and (length(lista_espera_tel(p_whatsapp)) < 6 or lista_espera_tel(l.cliente_whatsapp) <> lista_espera_tel(p_whatsapp))
$$;

-- Para el aviso del panel: cuantas horas hay ofrecidas ahora mismo (solo el numero).
create or replace function public.lista_espera_ofertas_vigentes(p_negocio uuid)
returns integer language sql stable security definer set search_path = public as $$
    select count(*)::integer from lista_espera
    where negocio_id = p_negocio and estado = 'ofrecida' and oferta_hasta > now()
$$;

