-- Al reservar, su espera de ese dia se cierra (y la hora que se le guardaba queda resuelta).
create or replace function public.lista_espera_cliente_reservo()
returns trigger language plpgsql security definer set search_path = public as $$
begin
    if length(lista_espera_tel(new.cliente_whatsapp)) < 6 then return null; end if;
    with cerradas as (
        update lista_espera set estado = 'reservada', reserva_id = new.id, updated_at = now()
        where negocio_id = new.negocio_id and fecha = new.fecha
          and estado in ('esperando', 'ofrecida', 'notificada', 'avisada')
          and lista_espera_tel(cliente_whatsapp) = lista_espera_tel(new.cliente_whatsapp)
        returning id)
    update lista_espera_huecos set estado = 'cerrado' where ofrecido_a in (select id from cerradas);
    return null;
exception when others then
    return null;
end $$;

