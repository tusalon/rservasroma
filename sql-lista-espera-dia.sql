drop policy if exists "lista_espera_panel_select" on public.lista_espera;
create policy "lista_espera_panel_select" on public.lista_espera for select to panel_salon
    using (negocio_id = public.panel_negocio() and public.panel_nivel() >= 2);
drop policy if exists "lista_espera_panel_update" on public.lista_espera;
create policy "lista_espera_panel_update" on public.lista_espera for update to panel_salon
    using (negocio_id = public.panel_negocio() and public.panel_nivel() >= 2)
    with check (negocio_id = public.panel_negocio());

