-- Ficha de clientas (historia clinica): salud y alergias, notas por visita y fotos antes y despues.
-- Ejecutar en el SQL Editor de Supabase, DESPUES de desplegar la funcion panel-login y poner su secreto.
-- Se puede correr dos veces sin romper nada. Deshacer: sql-fichas-clientas-DESHACER.sql
--
-- POR QUE ESTA TABLA NO ES COMO LAS DEMAS (19-10-2026)
-- Las demas tablas de RservasRoma se leen y escriben con la clave publica (anon), que viaja dentro de todas
-- las apps: cualquiera podria leerlas. Aqui hay datos de salud, asi que estas tablas NACEN CERRADAS:
--   * RLS activada y NINGUNA politica para anon ni para authenticated (se les quitan tambien los permisos).
--   * Solo entra el rol panel_salon, que es el que usa el JWT que firma la funcion panel-login despues de
--     comprobar la contrasena de la duena o de una profesional en el servidor.
--   * La politica exige que el negocio del token sea el de la fila y que el nivel sea 3 (la duena o una
--     profesional Avanzada). Una profesional de nivel 1 o 2 no ve nada, aunque pregunte directo a la API.
--   * Las fotos van a un bucket PRIVADO (fichas-fotos), una carpeta por negocio, y se ven con enlaces
--     firmados que caducan en una hora. No se usa Cloudinary: sus enlaces son publicos para quien los tenga.
--
