-- 1) Rol de la sesion del panel --------------------------------------------------------------------------
do $$
begin
    if not exists (select 1 from pg_roles where rolname = 'panel_salon') then
        create role panel_salon nologin;
    end if;
end
$$;

grant panel_salon to authenticator;
grant usage on schema public to panel_salon;

-- 2) Quien es quien pregunta (sale del JWT) --------------------------------------------------------------
create or replace function public.panel_negocio()
returns uuid
language sql
stable
as $$
    select nullif(auth.jwt() ->> 'negocio_id', '')::uuid
$$;

create or replace function public.panel_nivel()
returns integer
language sql
stable
as $$
    select coalesce(nullif(auth.jwt() ->> 'nivel', '')::integer, 0)
$$;

grant execute on function public.panel_negocio() to panel_salon;
grant execute on function public.panel_nivel() to panel_salon;

-- 3) Tablas ------------------------------------------------------------------------------------------------
create table if not exists public.fichas_clientas (
    negocio_id uuid not null references public.negocios(id) on delete cascade,
    whatsapp text not null,
    alergias text,
    condiciones text,
    medicamentos text,
    notas_generales text,
    actualizado_por text,
    updated_at timestamptz not null default now(),
    primary key (negocio_id, whatsapp)
);

create table if not exists public.fichas_visitas (
    id bigint generated by default as identity primary key,
    negocio_id uuid not null references public.negocios(id) on delete cascade,
    whatsapp text not null,
    fecha date not null default current_date,
    servicio text,
    profesional_nombre text,
    reserva_id bigint,
    notas text,
    evolucion text,
    creado_por text,
    created_at timestamptz not null default now()
);

create table if not exists public.fichas_fotos (
    id bigint generated by default as identity primary key,
    negocio_id uuid not null references public.negocios(id) on delete cascade,
    whatsapp text not null,
    visita_id bigint references public.fichas_visitas(id) on delete cascade,
    tipo text not null default 'otra' check (tipo in ('antes', 'despues', 'otra')),
    ruta text not null,
    created_at timestamptz not null default now()
);

create index if not exists fichas_visitas_clienta_idx on public.fichas_visitas (negocio_id, whatsapp, fecha desc);
create index if not exists fichas_fotos_clienta_idx on public.fichas_fotos (negocio_id, whatsapp, created_at desc);

-- 4) Cerradas para la clave publica; abiertas solo al rol del panel ------------------------------------------
alter table public.fichas_clientas enable row level security;
alter table public.fichas_visitas enable row level security;
alter table public.fichas_fotos enable row level security;

revoke all on public.fichas_clientas from anon, authenticated;
revoke all on public.fichas_visitas from anon, authenticated;
revoke all on public.fichas_fotos from anon, authenticated;

grant select, insert, update, delete on public.fichas_clientas to panel_salon;
grant select, insert, update, delete on public.fichas_visitas to panel_salon;
grant select, insert, update, delete on public.fichas_fotos to panel_salon;
grant usage, select on sequence public.fichas_visitas_id_seq to panel_salon;
grant usage, select on sequence public.fichas_fotos_id_seq to panel_salon;

drop policy if exists fichas_clientas_panel on public.fichas_clientas;
create policy fichas_clientas_panel on public.fichas_clientas
    for all to panel_salon
    using (negocio_id = public.panel_negocio() and public.panel_nivel() >= 3)
    with check (negocio_id = public.panel_negocio() and public.panel_nivel() >= 3);

drop policy if exists fichas_visitas_panel on public.fichas_visitas;
create policy fichas_visitas_panel on public.fichas_visitas
    for all to panel_salon
    using (negocio_id = public.panel_negocio() and public.panel_nivel() >= 3)
    with check (negocio_id = public.panel_negocio() and public.panel_nivel() >= 3);

drop policy if exists fichas_fotos_panel on public.fichas_fotos;
create policy fichas_fotos_panel on public.fichas_fotos
    for all to panel_salon
    using (negocio_id = public.panel_negocio() and public.panel_nivel() >= 3)
    with check (negocio_id = public.panel_negocio() and public.panel_nivel() >= 3);

-- 5) Fotos: bucket privado, una carpeta por negocio ---------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fichas-fotos', 'fichas-fotos', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
    set public = false,
        file_size_limit = excluded.file_size_limit,
        allowed_mime_types = excluded.allowed_mime_types;

grant usage on schema storage to panel_salon;
grant select, insert, update, delete on storage.objects to panel_salon;
grant select on storage.buckets to panel_salon;

drop policy if exists fichas_fotos_bucket_panel on storage.buckets;
create policy fichas_fotos_bucket_panel on storage.buckets
    for select to panel_salon
    using (id = 'fichas-fotos');

drop policy if exists fichas_fotos_objetos_panel on storage.objects;
create policy fichas_fotos_objetos_panel on storage.objects
    for all to panel_salon
    using (
        bucket_id = 'fichas-fotos'
        and (storage.foldername(name))[1] = public.panel_negocio()::text
        and public.panel_nivel() >= 3
    )
    with check (
        bucket_id = 'fichas-fotos'
        and (storage.foldername(name))[1] = public.panel_negocio()::text
        and public.panel_nivel() >= 3
    );

